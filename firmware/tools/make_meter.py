"""Render a 3x supersampled warm meter face and flash-resident RGB565 artwork.
Requires Pillow and a serif TrueType font; --font can supply one on other hosts.
"""
import argparse, math
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--font',default='/System/Library/Fonts/Supplemental/Times New Roman.ttf');a=p.parse_args()
k=3;size=224
im=Image.new('RGB',(size*k,size*k),'black');pixels=im.load()
for y in range(size*k):
 for x in range(size*k):
  xx,yy=x/k,y/k;radius=math.hypot(xx-112,yy-112)
  if radius<110:
   # A shaded recess with a stronger bulb pool at lower left, not flat white.
   edge=max(0,min(1,(radius-88)/22));lamp=math.exp(-((xx-65)**2+(yy-170)**2)/6500)
   grain=1.2*math.sin(xx*1.31+yy*.83)
   pixels[x,y]=tuple(int(max(0,min(255,v+grain))) for v in (188+51*lamp-40*edge,158+45*lamp-43*edge,96+26*lamp-34*edge))
d=ImageDraw.Draw(im)
def line(points,fill,width=1): d.line([(int(x*k),int(y*k)) for x,y in points],fill=fill,width=max(1,int(width*k)))
def text(x,y,s,n): d.text((x*k,y*k),s,font=ImageFont.truetype(a.font,n*k),fill='#302819',anchor='mm')
d.ellipse((2*k,2*k,222*k,222*k),outline='#8b6c36',width=2*k)
d.ellipse((5*k,5*k,219*k,219*k),outline='#463a28',width=k)
for i in range(61):
 angle=math.radians(155-i*(130/60));major=i%5==0;r=89
 line([(112+math.cos(angle)*(r-(11 if major else 4)),143-math.sin(angle)*(r-(11 if major else 4))),(112+math.cos(angle)*r,143-math.sin(angle)*r)],('#382d1a' if i<=50 else '#8c422e'),1 if major else .5)
 if i%10==0 and i<=50:text(112+math.cos(angle)*65,143-math.sin(angle)*65,str(i//5),12)
 if i in (55,60):text(112+math.cos(angle)*67,143-math.sin(angle)*67,'+20' if i==55 else '+40',8)
text(112,37,'SIGNAL',12);text(112,177,'S',23);text(112,196,'WIRELESS',9)
im=im.resize((size,size),Image.Resampling.LANCZOS)
(root/'outputs').mkdir(exist_ok=True);im.save(root/'outputs/meter_face.png')
values=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in im.getdata()]
(root/'include/MeterFace.h').write_text('#pragma once\n#include <stdint.h>\n// Generated by tools/make_meter.py; pixels are RGB565, native endian.\nstatic const uint16_t meterFace[224*224] = {\n'+ '\n'.join(','.join(hex(v) for v in values[i:i+16])+',' for i in range(0,len(values),16))+'\n};\n')
